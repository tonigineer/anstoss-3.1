#!/usr/bin/env python3
"""The coverage table: every dialog of the game's dialog file, every class
by area of the game, and the largest routines outside classes, each with how
far the replica has got with it.

A row's status is any of: traced (understood from the decompile), ported (in
the replica), function-tested (against the probe's traces), run-tested (run
diff), screen-tested (shot diff). "Ported" comes from the replica itself — the
dialogs its screens run (`anstoss-3-1 --screens`) and the routines its code
names in a `/// Original: FUN_…` line — the rest from `.plan/status.toml`,
kept by hand.

    python3 tools/scripts/coverage.py [--re ~/Programming/anstoss3-re] [--replica BINARY]

reads the installation's `deb/` files (`$ANSTOSS3_DIR`), `scripts/make_map.py`
and `export/` of the RE repo, and writes `.plan/COVERAGE.md`.
"""

import argparse
import csv
import os
import re
import subprocess
import sys
import tomllib
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parents[2]
DEFAULT_RE = Path(os.environ.get("ANSTOSS3_RE") or Path.home() / "Programming/anstoss3-re")
STATUSES = ["traced", "ported", "function-tested", "run-tested", "screen-tested"]
#: Dialogs the replica puts together from others, under ids of its own: the
#: week from the week screen and its club panel.
COMPOSED = {1000: (2, 460), 1001: (2, 460), 1002: (2, 460), 1003: (2, 460), 1004: (2, 460)}
#: How many routines outside classes the table lists, the largest first.
ROUTINES = 60
ORIGINAL = re.compile(r"Original:\s*((?:\w+::)?FUN_[0-9a-f]{8})")


def main() -> int:
    args = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    args.add_argument("--re", type=Path, default=DEFAULT_RE)
    args.add_argument("--replica", type=Path, help="the replica's binary (default: cargo run)")
    args = args.parse_args()
    sys.path.insert(0, str(args.re / "scripts"))
    import make_map  # the RE repo's map of the decompile

    names = make_map.defines(make_map.GAME / "deb/DialogIDs.rh")
    titles = make_map.titles(make_map.GAME / "deb/MeineDialoge.rch")
    export = args.re / "export/anstoss3.exe"
    rows = list(csv.DictReader(open(export / "functions.tsv", encoding="utf-8"), delimiter="\t"))
    classes = defaultdict(lambda: {"bytes": 0, "functions": 0})
    for row in rows:
        if row["namespace"] != "_global":
            classes[row["namespace"]]["bytes"] += int(row["bytes"])
            classes[row["namespace"]]["functions"] += 1
    class_dialogs = make_map.dialog_ids(export / "decompiled")
    runs = defaultdict(list)
    for cls, dialog in class_dialogs.items():
        runs[dialog].append(cls)

    screens = replica_screens(args.replica)
    ported_dialogs = set()
    for id_ in screens:
        ported_dialogs.update(COMPOSED.get(id_, (id_,)))
    originals = originals_in(HERE / "crates")
    status = load_status(HERE / ".plan/status.toml")

    def statuses(table: str, key, ported: bool) -> list[str]:
        found = set(status.get(table, {}).get(str(key), []))
        if ported:
            found.add("ported")
        return [s for s in STATUSES if s in found]

    dialogs = sorted(titles)
    lines = [
        "# Coverage",
        "",
        "Generated by `tools/scripts/coverage.py`; statuses besides “ported” from",
        "`.plan/status.toml`. Built from the game's own `deb/` files and the RE repo's",
        "decompile, so it stays out of any public repository.",
        "",
    ]
    counts = {s: sum(s in statuses("dialogs", d, d in ported_dialogs) for d in dialogs)
              for s in STATUSES}
    lines += [
        f"{len(dialogs)} dialogs, {sum(d in runs for d in dialogs)} of them run by a known class; "
        f"{len(classes)} classes; {len(originals)} routines ported by name.",
        "",
        "| status | dialogs |",
        "|---|---:|",
        *[f"| {s} | {counts[s]} |" for s in STATUSES],
        "",
        "## Dialogs",
        "",
        "| id | name | title | class | status |",
        "|---:|---|---|---|---|",
    ]
    for d in dialogs:
        cls = ", ".join(f"`{c}`" for c in sorted(runs.get(d, [])))
        title = titles[d].replace("|", "/")
        lines.append(f"| {d} | {names.get(d, '')} | {title} | {cls} | "
                     f"{', '.join(statuses('dialogs', d, d in ported_dialogs))} |")

    lines += ["", "## Classes by area", ""]
    grouped = defaultdict(list)
    for name in classes:
        area = next((a for a, p in make_map.AREAS if re.search(p, name)), "Sonstiges")
        grouped[area].append(name)
    by_class = defaultdict(int)
    for original in originals:
        if "::" in original:
            by_class[original.split("::")[0]] += 1
    for area in [a for a, _ in make_map.AREAS] + ["Sonstiges"]:
        members = sorted(grouped.get(area, []), key=lambda n: -classes[n]["bytes"])
        if not members:
            continue
        size = sum(classes[n]["bytes"] for n in members)
        lines += [f"### {area} — {len(members)} classes, {size / 1024:.0f} KB", "",
                  "| class | dialog | functions | KB | status |", "|---|---|---:|---:|---|"]
        for name in members:
            c = classes[name]
            dialog = class_dialogs.get(name)
            dialog = f"{dialog} {names.get(dialog, '')}".strip() if dialog is not None else ""
            found = statuses("classes", name, False)
            if by_class[name]:
                found.append(f"{by_class[name]} routines ported")
            lines.append(f"| {name} | {dialog} | {c['functions']} | {c['bytes'] / 1024:.1f} | "
                         f"{', '.join(found)} |")
        lines.append("")

    globals_ = sorted((r for r in rows if r["namespace"] == "_global"), key=lambda r: -int(r["bytes"]))
    marked = set(status.get("routines", {})) | originals
    listed = globals_[:ROUTINES] + [r for r in globals_[ROUTINES:] if r["name"] in marked]
    lines += [f"## Routines outside classes: the {ROUTINES} largest, and those with a status", "",
              "| address | routine | KB | strings | status |", "|---|---|---:|---|---|"]
    for r in listed:
        strings = r["strings"].replace("|", "/")[:100]
        found = statuses("routines", r["name"], r["name"] in originals)
        lines.append(f"| {r['address']} | {r['name']} | {int(r['bytes']) / 1024:.1f} | {strings} | "
                     f"{', '.join(found)} |")

    out = HERE / ".plan/COVERAGE.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(dialogs)} dialogs, {len(ported_dialogs & set(dialogs))} ported; "
          f"{len(classes)} classes; {len(originals)} routines ported; wrote {out}")
    return 0


def replica_screens(binary: Path | None) -> list[int]:
    """The dialogs the replica's screens run."""
    command = [str(binary), "--screens"] if binary else [
        "cargo", "run", "-q", "--bin", "anstoss-3-1", "--", "--screens"]
    out = subprocess.run(command, cwd=HERE, capture_output=True, text=True, check=True).stdout
    return [int(line) for line in out.split()]


def originals_in(crates: Path) -> set[str]:
    """The routines the replica's code names as the originals of its own."""
    found = set()
    for path in crates.rglob("*.rs"):
        found.update(m.group(1) for m in ORIGINAL.finditer(path.read_text(encoding="utf-8")))
    return found | {o.split("::")[-1] for o in found}


def load_status(path: Path) -> dict:
    if not path.exists():
        return {}
    status = tomllib.loads(path.read_text(encoding="utf-8"))
    for table in status.values():
        for key, values in table.items():
            unknown = set(values) - set(STATUSES)
            if unknown:
                raise SystemExit(f"{path}: {key}: no such status {', '.join(sorted(unknown))}")
    return status


if __name__ == "__main__":
    sys.exit(main())
